text = input()
cleaned = ""
count = 0
for ch in text:
    if ch == '.':
        break
    else:
        cleaned += ch
    if ch.lower() in 'aeiou':
        count += 1
print("Vowel count:", count)
if '.' in text:
    print("Cleaned sentence:", cleaned.upper())
else:
    print("There is no cleaned sentence.")

